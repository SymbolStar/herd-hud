#!/bin/bash
# Build the Agent HUD .app bundle (ad-hoc signed, no Xcode project needed).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")" && pwd)"
PROJECT_ROOT="$(cd "$ROOT/.." && pwd)"
APP="$ROOT/build/Agent HUD.app"
SDK="$(xcrun --show-sdk-path)"
SWIFTC="$(xcrun --find swiftc)"
TARGET="arm64-apple-macos13.0"

if [[ "$(uname -m)" != "arm64" ]]; then
  TARGET="x86_64-apple-macos13.0"
fi

# Read the project-wide version; fall back to Info.plist's default.
VERSION_FILE="$PROJECT_ROOT/VERSION"
if [[ -f "$VERSION_FILE" ]]; then
  VERSION="$(head -1 "$VERSION_FILE" | tr -d '[:space:]')"
else
  VERSION="0.0.0"
fi
BUILD_NUMBER="$(git -C "$PROJECT_ROOT" rev-list --count HEAD 2>/dev/null || echo 0)"
COMMIT_SHA="$(git -C "$PROJECT_ROOT" rev-parse --short HEAD 2>/dev/null || echo unknown)"

# Generate BuildVersion.swift with version constants.
BUILD_VERSION_SWIFT="$ROOT/Sources/BuildVersion.swift"
cat > "$BUILD_VERSION_SWIFT" <<SWIFT
// Auto-generated by build.sh — do not edit.
enum BuildInfo {
    static let version = "$VERSION"
    static let build = "$BUILD_NUMBER"
    static let commit = "$COMMIT_SHA"
    static var summary: String { "\\(version) (\\(build), \\(commit))" }
}
SWIFT

rm -rf "$ROOT/build"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

"$SWIFTC" -O -swift-version 5 \
  -target "$TARGET" \
  -sdk "$SDK" \
  -framework AppKit \
  -framework SwiftUI \
  -framework Combine \
  -D GENERATED_BUILD_INFO \
  "$ROOT"/Sources/*.swift \
  -o "$APP/Contents/MacOS/AgentHUD"

# Stamp the Info.plist with the current version.
cp "$ROOT/Info.plist" "$APP/Contents/Info.plist"
/usr/libexec/PlistBuddy -c "Set :CFBundleShortVersionString $VERSION" "$APP/Contents/Info.plist"
/usr/libexec/PlistBuddy -c "Set :CFBundleVersion $BUILD_NUMBER" "$APP/Contents/Info.plist"
codesign --force --sign - "$APP" >/dev/null 2>&1 || true

echo "built: $APP  v$VERSION ($BUILD_NUMBER, $COMMIT_SHA)"
