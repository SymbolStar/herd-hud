#!/bin/bash
# Run the HUD's unit tests.
#
# The app has no Xcode project, so this compiles the real sources (minus
# main.swift, whose top-level code would launch the app) together with
# Tests/main.swift into one throwaway binary and runs it.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")" && pwd)"
SDK="$(xcrun --show-sdk-path)"
SWIFTC="$(xcrun --find swiftc)"
TARGET="arm64-apple-macos13.0"

if [[ "$(uname -m)" != "arm64" ]]; then
  TARGET="x86_64-apple-macos13.0"
fi

# build.sh generates this; the tests only need the type to exist.
BUILD_VERSION_SWIFT="$ROOT/Sources/BuildVersion.swift"
if [[ ! -f "$BUILD_VERSION_SWIFT" ]]; then
  cat > "$BUILD_VERSION_SWIFT" <<'SWIFT'
// Auto-generated by test.sh — do not edit.
enum BuildInfo {
    static let version = "test"
    static let build = "0"
    static let commit = "test"
    static var summary: String { "\(version) (\(build), \(commit))" }
}
SWIFT
fi

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

SOURCES=()
for source in "$ROOT"/Sources/*.swift; do
  case "$(basename "$source")" in
    main.swift) continue ;;  # top-level code; would run the app
  esac
  SOURCES+=("$source")
done

"$SWIFTC" -O -swift-version 5 \
  -target "$TARGET" \
  -sdk "$SDK" \
  -framework AppKit \
  -framework SwiftUI \
  -framework Combine \
  -D GENERATED_BUILD_INFO \
  "${SOURCES[@]}" \
  "$ROOT"/Tests/*.swift \
  -o "$WORK/hud-tests"

"$WORK/hud-tests"
